@app.route('/join-meet', methods=['POST'])
def join_meet_route():
    """
    Starts the Google Meet bot in a background thread so Flask can respond immediately.

    Phase 6 update: now also accepts 'context' and 'image_url' so the real-time
    listener can generate personalised GPT answers and D-ID avatar videos.

    Expected JSON body:
        video_url  (str) : Public URL of the initial D-ID avatar video.
        context    (str) : Free-text bio the user wants GPT to use when answering.
        image_url  (str) : Public Cloudinary URL of the user's photo for D-ID.
    """
    # Read the JSON request body safely and fall back to an empty dict when missing.
    data = request.get_json() or {}

    # Pull the generated avatar video URL from the request body.
    video_url = data.get('video_url')

    # Pull the user context and image URL — both default to empty string if missing.
    # The pipeline will still run without them, but the GPT answers will be generic.
    context   = data.get('context', '')
    image_url = data.get('image_url', '')

    # Validate that the frontend actually sent a usable video URL.
    if not video_url:
        return jsonify({"error": "video_url is required"}), 400

    try:
        # Import the Meet bot only when needed so the normal app startup stays lightweight.
        from meet_bot import run_meet_bot

        # Define a wrapper that passes all three arguments to the bot.
        def run_in_background():
            try:
                print("=== BOT STARTING ===")
                print(f"video_url: {video_url[:50]}")
                print(f"image_url: {image_url[:50]}")
                print(f"context: {context[:50]}")
                
                # run_meet_bot now receives context and image_url so the real-time
                # pipeline can generate personalised avatar responses.
                result = run_meet_bot(video_url, context, image_url)
                
                # Print the bot result so repeated clicks are easier to debug.
                print(f"=== BOT RESULT: {result} ===")
            except Exception as e:
                import traceback
                print(f"=== BOT CRASHED ===")
                print(traceback.format_exc())

        # Create a background thread so Selenium can run without freezing Flask.
        thread = threading.Thread(target=run_in_background)

        # Mark the thread as daemon so it will not block app shutdown.
        thread.daemon = True

        # Start the automation thread right away.
        thread.start()

        # Return immediately so the browser gets a quick response.
        return jsonify({
            "message": "Bot joining meeting and listening for questions in real-time!"
        }), 200
    except Exception as e:
        # Return a server error if the thread setup fails.
        return jsonify({"error": str(e)}), 500


@app.route('/stop-bot', methods=['POST'])
def stop_bot():
    """
    Gracefully stops the real-time bot:
    1. Stops the VAD microphone listener thread.
    2. Closes the Chrome window controlled by Selenium.

    Call this from the frontend "Stop Bot" button.
    """
    try:
        # Import stop_listening here so it is only loaded when needed.
        from realtime_listener import stop_listening

        # Signal the VAD loop to exit on the next iteration.
        stop_listening()
        print("[StopBot] Listener stopped.")

        # Import the global driver reference from meet_bot.
        import meet_bot

        # Close the Chrome browser if a session is currently open.
        if meet_bot._driver is not None:
            try:
                meet_bot._driver.quit()
                print("[StopBot] Chrome closed.")
            except Exception as e:
                # Log the error but don't crash — the browser may already be gone.
                print(f"[StopBot] Error closing Chrome: {e}")
            # Clear the reference so future calls don't try to close a dead driver.
            meet_bot._driver = None

        return jsonify({"message": "Bot stopped!"}), 200

    except Exception as e:
        print(f"[StopBot] Unexpected error: {e}")
        return jsonify({"error": str(e)}), 500

