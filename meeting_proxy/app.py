@app.route('/library-video/<filename>')
def serve_library_video(filename):
    """
    Serves video files for OBS browser source.
    Checks response_library first, then active
    session folders, then all user session folders.
    """
    import re
    from flask import Response
    import mimetypes

    # Sanitize filename to prevent path traversal
    safe_filename = re.sub(r'[^a-zA-Z0-9_\-\.]', '', filename)

    def stream_video(file_path):
        """Stream video with range request support."""
        file_size = os.path.getsize(file_path)
        range_header = request.headers.get('Range', None)

        if range_header:
            # Parse range request (e.g. "bytes=0-")
            byte_start = 0
            byte_end = file_size - 1

            match = re.search(
                r'bytes=(\d+)-(\d*)', range_header
            )
            if match:
                byte_start = int(match.group(1))
                if match.group(2):
                    byte_end = int(match.group(2))

            length = byte_end - byte_start + 1

            with open(file_path, 'rb') as f:
                f.seek(byte_start)
                data = f.read(length)

            response = Response(
                data,
                206,
                mimetype='video/mp4',
                direct_passthrough=True
            )
            response.headers['Content-Range'] = (
                f'bytes {byte_start}-{byte_end}/{file_size}'
            )
            response.headers['Accept-Ranges'] = 'bytes'
            response.headers['Content-Length'] = length
            return response
        else:
            return send_from_directory(
                os.path.dirname(file_path),
                os.path.basename(file_path),
                mimetype='video/mp4'
            )

    # --- SEARCH ORDER ---

    # 1. Check response_library (default)
    library_path = os.path.join(
        os.getcwd(), 'response_library', safe_filename
    )
    if os.path.exists(library_path):
        print(f"[Route] Serving from library: {safe_filename}")
        return stream_video(library_path)

    # 2. Check active session folders in memory
    for session_id, sess in _prep_sessions.items():
        session_folder = sess.get('session_folder', '')
        if session_folder:
            session_path = os.path.join(
                session_folder, safe_filename
            )
            if os.path.exists(session_path):
                print(
                    f"[Route] Serving from session "
                    f"{session_id}: {safe_filename}"
                )
                return stream_video(session_path)

    # 3. Search all user session folders on disk
    users_folder = os.path.join(os.getcwd(), 'users')
    if os.path.exists(users_folder):
        for user_id_dir in os.listdir(users_folder):
            sessions_dir = os.path.join(
                users_folder, user_id_dir, 'sessions'
            )
            if not os.path.exists(sessions_dir):
                continue
            for session_dir in os.listdir(sessions_dir):
                file_path = os.path.join(
                    sessions_dir, session_dir, safe_filename
                )
                if os.path.exists(file_path):
                    print(
                        f"[Route] Serving from disk session "
                        f"{session_dir}: {safe_filename}"
                    )
                    return stream_video(file_path)

    # 4. Check user library folders
    if os.path.exists(users_folder):
        for user_id_dir in os.listdir(users_folder):
            library_dir = os.path.join(
                users_folder, user_id_dir, 'library'
            )
            if os.path.exists(library_dir):
                file_path = os.path.join(
                    library_dir, safe_filename
                )
                if os.path.exists(file_path):
                    print(
                        f"[Route] Serving from user library: "
                        f"{safe_filename}"
                    )
                    return stream_video(file_path)

    # Not found anywhere
    print(f"[Route] ❌ File not found: {safe_filename}")
    return jsonify({'error': 'Video not found'}), 404

