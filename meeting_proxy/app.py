@app.route('/api/meeting-prep/join/<session_id>',
           methods=['POST'])
@require_firebase_auth
def join_prep_meeting_string(session_id):
    """
    Starts the meeting bot using session-specific videos.
    Accepts meet_link from request body.
    This route handles reusing past meeting sessions.
    """
    # This is a global variable that stores session data in memory
    # It's like a temporary storage for active sessions
    global _prep_sessions
    
    # Get the current user's ID from the session
    user_id = flask_session.get('user_id')
    
    # Find the user in the database
    user = db.session.get(User, user_id)
    
    # Get the data sent in the POST request (JSON format)
    data = request.get_json() or {}

    # Try to get the meeting link from multiple places:
    # 1. From the request data (what the user just entered)
    # 2. From the session in memory (if it was stored before)
    # 3. From the user's profile (saved preference)
    meet_link = (
        data.get('meet_link') or
        _prep_sessions.get(session_id, {}).get('meet_link') or
        user.meet_link
    )

    # If we still don't have a meeting link, we can't proceed
    if not meet_link:
        return jsonify(
            {'error': 'No meeting link provided'}
        ), 400

    # Check if this session is already loaded in memory
    if session_id not in _prep_sessions:
        # If not in memory, try to load it from the database
        # This happens when reusing a past session
        meeting_session = MeetingSession.query.filter_by(
            session_id=session_id,
            user_id=user_id
        ).first()

        # If the session doesn't exist in the database, error
        if not meeting_session:
            return jsonify(
                {'error': 'Session not found'}
            ), 404

        # Parse the Q&A data from the database (it's stored as JSON text)
        import json
        qa_list = json.loads(
            meeting_session.qa_pairs or '[]'
        )
        
        # Get the folder where the videos are stored
        session_folder = meeting_session.session_folder

        # Rebuild the videos dictionary from files on disk
        # Each Q&A has a corresponding video file
        videos = {}
        for i, qa in enumerate(qa_list):
            # Video files are named q1.mp4, q2.mp4, etc.
            video_path = os.path.join(
                session_folder, f"q{i+1}.mp4"
            )
            # Only include videos that actually exist on disk
            if os.path.exists(video_path):
                videos[qa['question']] = video_path

        # Also check for the idle nodding video
        idle_path = os.path.join(
            session_folder, "nodding_idle.mp4"
        )
        if os.path.exists(idle_path):
            videos['__idle__'] = idle_path

        # Store all this data back in memory for quick access
        _prep_sessions[session_id] = {
            'user_id': user_id,
            'meet_link': meet_link,
            'qa_list': qa_list,
            'videos': videos,
            'progress': 100,  # Already complete since we're reusing
            'status_messages': ['Session reloaded!'],
            'complete': True,
            'error': None,
            'session_folder': session_folder
        }
        print(f"[Join] Reloaded session {session_id} "
              f"with {len(videos)} videos")

    # Update the meeting link in the session (in case it changed)
    _prep_sessions[session_id]['meet_link'] = meet_link

    # Get the session data and videos
    sess = _prep_sessions[session_id]
    session_videos = sess.get('videos', {})

    print(f"[Join] Joining with {len(session_videos)} videos")

    # Save a new meeting record to the database
    # This tracks that the bot is now active in a meeting
    meeting = Meeting(
        user_id=user_id,
        meet_link=meet_link,
        meeting_context=sess.get('meeting_context', ''),
        session_id=session_id,
        status='active',
        started_at=datetime.utcnow()
    )
    db.session.add(meeting)
    db.session.commit()

    # Extract user values before the thread starts.
    user_context = user.context or ''
    user_photo_url = user.photo_url or ''
    user_id_val = user_id

    # Define a function to run the bot in the background
    # This way the API response is fast, but the bot starts joining
    def run_bot():
        # Use the app context because we're in a background thread
        with app.app_context():
            # Import the bot function
            from meet_bot import run_meet_bot
            # Start the bot with all the necessary information
            run_meet_bot(
                video_url='use_library',  # Use the videos from the session
                context=user_context,  # User's context/preferences
                image_url=user_photo_url,  # User's avatar image
                user_id=user_id_val,  # Who is running this
                meet_link=meet_link,  # Which meeting to join
                session_videos=session_videos  # The prepared videos to use
            )

    # Start the bot in a background thread so it doesn't block the response
    threading.Thread(target=run_bot, daemon=True).start()

    # Return success message to the frontend
    return jsonify({
        'message': 'Bot is joining the meeting!',
        'videos_loaded': len(session_videos)
    })

