@app.route("/api/auth/firebase", methods=["POST"])
def firebase_login():
    """
    Called by React frontend after Firebase login.
    Receives Firebase ID token, verifies it, creates
    or gets user in our database, stores in session.
    """
    data = request.get_json() or {}
    id_token = data.get("token")

    if not id_token:
        return jsonify({"error": "No token provided"}), 400

    try:
        from firebase_auth import verify_firebase_token

        decoded = verify_firebase_token(id_token)

        google_id = decoded.get("uid")
        email = decoded.get("email")
        name = decoded.get("name", email)
        picture = decoded.get("picture", "")

        # Get existing user or create a new one on first login.
        user = User.query.filter_by(google_id=google_id).first()

        is_new_user = False
        if not user:
            user = User(
                google_id=google_id,
                email=email,
                name=name,
                profile_picture=picture,
            )
            db.session.add(user)
            db.session.commit()
            user.get_library_folder()
            user.get_cache_folder()
            is_new_user = True
            print(f"[Auth] New user registered: {email}")
        else:
            user.name = name
            user.profile_picture = picture
            db.session.commit()
            print(f"[Auth] User logged in: {email}")

        # Store user ID in server-side session for future API requests.
        flask_session["user_id"] = user.id

        return jsonify(
            {
                "user": user.to_dict(),
                "is_new_user": is_new_user,
                "message": "Login successful!",
            }
        )

    except Exception as e:
        print(f"[Auth] Firebase login error: {e}")
        import traceback
        print(traceback.format_exc())
        return jsonify({"error": str(e)}), 401


