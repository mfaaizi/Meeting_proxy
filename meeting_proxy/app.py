@app.route('/api/meetings/<int:meeting_id>/generate-summary',
           methods=['POST'])
@require_firebase_auth
def generate_meeting_summary(meeting_id):
    """
    Generates a summary from the meeting transcript using OpenAI GPT-4o-mini.
    """
    user_id = flask_session.get('user_id')
    meeting = Meeting.query.filter_by(
        id=meeting_id, user_id=user_id
    ).first()

    if not meeting:
        return jsonify({'error': 'Meeting not found'}), 404

    try:
        from openai import OpenAI
        import os

        openai_client = OpenAI(
            api_key=os.getenv('OPENAI_API_KEY')
        )

        transcript = meeting.transcript or 'No transcript available'

        summary_response = openai_client.chat.completions.create(
            model="gpt-4o-mini",
            messages=[{
                "role": "user",
                "content": f"""Summarize this meeting transcript
in a professional format with:
1. Key topics discussed
2. Questions asked
3. Main answers given
4. Action items if any

Transcript:
{transcript}"""
            }],
            max_tokens=500,
            temperature=0.7
        )

        summary = summary_response.choices[0].message.content
        meeting.summary = summary
        db.session.commit()

        return jsonify({
            'summary': summary,
            'transcript': transcript
        })

    except Exception as e:
        return jsonify({'error': str(e)}), 500

