@app.route('/transcribe', methods=['POST'])
def transcribe():
    """
    Handles audio transcription requests.
    Expects an 'audio' file upload.
    Returns the transcribed text.
    """
    # Check if 'audio' file is in the request
    audio_file = request.files.get('audio')
    
    if not audio_file:
        return jsonify({"error": "No audio file provided"}), 400
        
    # Define a temporary path to save the uploaded audio
    # We use the original filename, but you could use a unique ID too
    temp_path = os.path.join("temp_audio", audio_file.filename)
    
    try:
        # Save the file temporarily to disk
        audio_file.save(temp_path)
        print(f"Saved temp audio to: {temp_path}")
        
        # Open the file in binary read mode for OpenAI API
        with open(temp_path, "rb") as audio_file_obj:
            # Call the transcription service
            transcript_text = transcribe_audio(audio_file_obj)
            
        print(f"Transcription result: {transcript_text}")
        
        # Clean up: delete the temporary file
        os.remove(temp_path)
        print(f"Deleted temp file: {temp_path}")
        
        # Return the transcript as JSON
        return jsonify({"transcript": transcript_text}), 200
        
    except Exception as e:
        print(f"Transcription error: {e}")
        # Ensure we clean up the file even if an error occurs
        if os.path.exists(temp_path):
            os.remove(temp_path)
            
        return jsonify({"error": str(e)}), 500

