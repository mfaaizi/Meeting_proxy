@app.route('/api/sessions/<session_id>/reuse', methods=['POST'])
@require_firebase_auth
def reuse_session(session_id):
    """
    Allows user to reuse a past meeting session.
    Loads the session videos back into memory
    so the bot can join a new meeting with them.
    """
    global _prep_sessions
    user_id = flask_session.get('user_id')
    user = db.session.get(User, user_id)

    meeting_session = MeetingSession.query.filter_by(
        session_id=session_id,
        user_id=user_id
    ).first()

    if not meeting_session:
        return jsonify({'error': 'Session not found'}), 404

    if not os.path.exists(meeting_session.session_folder):
        return jsonify(
            {'error': 'Session videos no longer on disk'}
        ), 404

    import json

    # Reload session into memory
    qa_list = json.loads(meeting_session.qa_pairs or '[]')

    # Build videos dict from disk
    videos = {}
    session_folder = meeting_session.session_folder

    for i, qa in enumerate(qa_list):
        video_path = os.path.join(
            session_folder, f"q{i+1}.mp4"
        )
        if os.path.exists(video_path):
            videos[qa['question']] = video_path

    idle_path = os.path.join(
        session_folder, "nodding_idle.mp4"
    )
    if os.path.exists(idle_path):
        videos['__idle__'] = idle_path

    # Store in session (in-memory _prep_sessions)
    # This is for the status endpoint
    _prep_sessions[session_id] = {
        'user_id': user_id,
        'meet_link': user.meet_link or '',
        'qa_list': qa_list,
        'videos': videos,
        'progress': 100,
        'status_messages': ['Session reloaded!'],
        'complete': True,
        'error': None,
        'session_folder': session_folder
    }

    return jsonify({
        'session_id': session_id,
        'message': f'Session loaded with {len(videos)} videos!',
        'video_count': len(videos),
        'qa_count': len(qa_list)
    })

@app.route('/api/meetings/schedule', methods=['POST'])
@require_firebase_auth
def schedule_meeting():
    """
    Schedules a meeting for the bot to auto-join at a
    specific date and time.
    """
    user_id = flask_session.get('user_id')
    user = db.session.get(User, user_id)
    data = request.get_json()

    meet_link = data.get('meet_link')
    scheduled_date = data.get('scheduled_date')
    scheduled_time = data.get('scheduled_time')

    if not all([meet_link, scheduled_date, scheduled_time]):
        return jsonify({'error': 'All fields required'}), 400

    from datetime import datetime
    try:
        scheduled_dt = datetime.strptime(
            f"{scheduled_date} {scheduled_time}",
            "%Y-%m-%d %H:%M"
        )
    except ValueError:
        return jsonify({'error': 'Invalid date or time format'}), 400

    # Calculate seconds until meeting
    now = datetime.now()
    delay_seconds = (scheduled_dt - now).total_seconds()

    if delay_seconds < 0:
        return jsonify({'error': 'Meeting time is in the past'}), 400

    # Save to database
    meeting = Meeting(
        user_id=user_id,
        meet_link=meet_link,
        status='scheduled'
    )
    db.session.add(meeting)
    db.session.commit()

    # Extract user data before the background thread starts.
    user_context = user.context or ''
    user_photo_url = user.photo_url or ''
    user_id_val = user_id

    # Beginner-friendly comment: We start a "delayed join" process in the background.
    # It sleeps for the exact amount of time until the meeting starts.
    def delayed_join():
        import time
        print(f"[Scheduler] Waiting {delay_seconds:.0f}s until meeting...")
        time.sleep(delay_seconds)
        print(f"[Scheduler] Time to join meeting!")
        
        # Use app context because we are in a background thread
        with app.app_context():
            from meet_bot import run_meet_bot
            # Refresh meeting object from db
            meeting_obj = db.session.get(Meeting, meeting.id)
            if not meeting_obj:
                return
            
            meeting_obj.status = 'active'
            meeting_obj.started_at = datetime.now()
            db.session.commit()

            # Run the bot with the provided meeting details
            run_meet_bot(
                video_url='use_library', # Tells bot to use pre-generated library
                context=user_context,
                image_url=user_photo_url,
                user_id=user_id_val,
                meet_link=meet_link
            )

    thread = threading.Thread(
        target=delayed_join, daemon=True
    )
    thread.start()

    return jsonify({
        'message': f'Bot scheduled to join in {int(delay_seconds/60)} minutes!',
        'meeting_id': meeting.id
    })

